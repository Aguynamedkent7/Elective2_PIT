/** Placeholder screen with a back arrow; replaced by the real canvas/history in later phases. */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun SimpleScreen(title: String, body: String, onBack: () -> Unit) {
    Scaffold(
        containerColor = MaterialTheme.colorScheme.background,
        topBar = {
            TopAppBar(
                title = { Text(title) },
                navigationIcon = {
                    IconButton(onClick = onBack) {
                        Icon(Icons.AutoMirrored.Outlined.ArrowBack, stringResource(R.string.cd_back))
                    }
                },
                colors = TopAppBarDefaults.topAppBarColors(containerColor = MaterialTheme.colorScheme.background),
            )
        },
    ) { pad ->
        Box(Modifier.fillMaxSize().padding(pad), contentAlignment = Alignment.Center) {
            Text(body, color = MaterialTheme.colorScheme.onSurfaceVariant)
        }
    }
}
